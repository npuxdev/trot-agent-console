export function getTopologyNodeById(id: string): TopologyNode | undefined {
  return topologyNodes.find((n) => n.id === id)
}

export function getEdgesForNode(nodeId: string): TopologyEdge[] {
  return topologyEdges.filter(
    (e) => e.source === nodeId || e.target === nodeId
  )
}
